/* AR table (#ar) — window.AR.
 *
 * A printed sheet with four corner markers lies on a table. The phone camera finds the markers, a homography maps
 * the rectangle between their centres to an equirectangular map of the Moon or Mars (lon -180..180 -> x,
 * lat 90..-90 -> y) and the same object markers as on the site are drawn over it. A robot carries its own marker;
 * when it comes close to an object, the object's card opens.
 *
 * Marker detection is implemented here in plain JavaScript (no library): adaptive threshold -> connected
 * components -> quadrilateral -> 7x7 cell sampling. The marker format is the original ArUco 7x7 layout
 * (black border, 5x5 data cells, each row one of four 5-bit words, 2 data bits per row), as used by js-aruco.
 * Markers are generated by this module ("Markers to print"); compatibility with other generators is not verified.
 *
 * Without a camera (no HTTPS, no permission, no device) the module runs a demo: the map fills the stage and the
 * robot is dragged with the mouse, a finger or the arrow keys. The proximity logic is the same in both modes.
 */
