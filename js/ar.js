  // ================================================================== maths
  // Homography that maps src[i] -> dst[i] (4 point pairs, {x, y}). Returns 9 numbers (row-major, h8 = 1).
  function solveH(src, dst) {
    var A = [], i;
    for (i = 0; i < 4; i++) {
      var x = src[i].x, y = src[i].y, X = dst[i].x, Y = dst[i].y;
      A.push([x, y, 1, 0, 0, 0, -x * X, -y * X, X]);
      A.push([0, 0, 0, x, y, 1, -x * Y, -y * Y, Y]);
    }
    for (var c = 0; c < 8; c++) {           // Gaussian elimination with partial pivoting
      var p = c;
      for (var r = c + 1; r < 8; r++) if (Math.abs(A[r][c]) > Math.abs(A[p][c])) p = r;
      if (Math.abs(A[p][c]) < 1e-12) return null;
      var t = A[c]; A[c] = A[p]; A[p] = t;
      for (r = 0; r < 8; r++) {
        if (r === c) continue;
        var f = A[r][c] / A[c][c];
        for (var k = c; k < 9; k++) A[r][k] -= f * A[c][k];
      }
    }
    var h = [];
    for (i = 0; i < 8; i++) h.push(A[i][8] / A[i][i]);
    h.push(1);
    return h;
  }
  function applyH(H, x, y) {
    var w = H[6] * x + H[7] * y + H[8];
    return { x: (H[0] * x + H[1] * y + H[2]) / w, y: (H[3] * x + H[4] * y + H[5]) / w };
  }
  function invH(H) {
    var a = H[0], b = H[1], c = H[2], d = H[3], e = H[4], f = H[5], g = H[6], h = H[7], i = H[8];
    var A = e * i - f * h, B = -(d * i - f * g), C = d * h - e * g;
    var det = a * A + b * B + c * C;
    if (Math.abs(det) < 1e-12) return null;
    return [A / det, -(b * i - c * h) / det, (b * f - c * e) / det,
            B / det, (a * i - c * g) / det, -(a * f - c * d) / det,
            C / det, -(a * h - b * g) / det, (a * e - b * d) / det];
  }
  var UNIT = [{ x: 0, y: 0 }, { x: 1, y: 0 }, { x: 1, y: 1 }, { x: 0, y: 1 }];

  // ================================================================== marker format
  // 7×7 cells, 1 = white. Row r of the 5×5 data area is WORDS[(id >> 2*(4-r)) & 3].
  function markerBits(id) {
    var g = [], r, c;
    for (r = 0; r < 7; r++) { g.push([]); for (c = 0; c < 7; c++) g[r].push(0); }
    for (r = 0; r < 5; r++) {
      var w = WORDS[(id >> (2 * (4 - r))) & 3];
      for (c = 0; c < 5; c++) g[r + 1][c + 1] = w[c];
    }
    return g;
  }
  function decodeBits(b) {                 // b: 5×5, 1 = white. Returns id or -1.
    var id = 0;
    for (var r = 0; r < 5; r++) {
      var best = 99;
      for (var w = 0; w < 4; w++) {
        var d = 0;
        for (var c = 0; c < 5; c++) if (b[r][c] !== WORDS[w][c]) d++;
        if (d < best) best = d;
      }
      if (best !== 0) return -1;
      id = (id << 1) | b[r][1]; id = (id << 1) | b[r][3];
    }
    return id;
  }
  // SVG fragment (units = mm): black cells of marker `id`, top-left at (x, y), side `size`.
  function markerSVG(id, x, y, size) {
    // white quiet zone, black square, then the white cells (crisp edges: no hairline seams between cells)
    var g = markerBits(id), s = size / 7;
    var out = '<g shape-rendering="crispEdges"><rect x="' + (x - s) + '" y="' + (y - s) + '" width="' + (size + 2 * s) + '" height="' + (size + 2 * s) + '" fill="#fff"/>' +
      '<rect x="' + x + '" y="' + y + '" width="' + size + '" height="' + size + '" fill="#000"/>';
    for (var r = 0; r < 7; r++) for (var c = 0; c < 7; c++) if (g[r][c]) {
      out += '<rect x="' + (x + c * s).toFixed(3) + '" y="' + (y + r * s).toFixed(3) + '" width="' + s.toFixed(3) + '" height="' + s.toFixed(3) + '" fill="#fff"/>';
    }
    return out + "</g>";
  }

  // ================================================================== detector
  var buf = { w: 0, h: 0 };
  function ensureBuf(w, h) {
    if (buf.w === w && buf.h === h) return;
    buf = { w: w, h: h, gray: new Uint8Array(w * h), integ: new Uint32Array((w + 1) * (h + 1)),
            bin: new Uint8Array(w * h), lab: new Int32Array(w * h), stack: new Int32Array(w * h) };
  }

  function quadFromPoints(xs, ys) {
    var n = xs.length, i, cx = 0, cy = 0;
    for (i = 0; i < n; i++) { cx += xs[i]; cy += ys[i]; }
    cx /= n; cy /= n;
    var i0 = 0, d0 = -1, d;
    for (i = 0; i < n; i++) { d = (xs[i] - cx) * (xs[i] - cx) + (ys[i] - cy) * (ys[i] - cy); if (d > d0) { d0 = d; i0 = i; } }
    var i1 = 0, d1 = -1;
    for (i = 0; i < n; i++) { d = (xs[i] - xs[i0]) * (xs[i] - xs[i0]) + (ys[i] - ys[i0]) * (ys[i] - ys[i0]); if (d > d1) { d1 = d; i1 = i; } }
    var ax = xs[i0], ay = ys[i0], bx = xs[i1], by = ys[i1], i2 = -1, i3 = -1, s2 = 0, s3 = 0;
    for (i = 0; i < n; i++) {
      var cr = (bx - ax) * (ys[i] - ay) - (by - ay) * (xs[i] - ax);
      if (cr > s2) { s2 = cr; i2 = i; }
      if (cr < s3) { s3 = cr; i3 = i; }
    }
    if (i2 < 0 || i3 < 0) return null;
    var q = [{ x: ax, y: ay }, { x: xs[i2], y: ys[i2] }, { x: bx, y: by }, { x: xs[i3], y: ys[i3] }];
    // clockwise on screen (y down) = positive shoelace sum
    var area = 0;
    for (i = 0; i < 4; i++) { var p = q[i], o = q[(i + 1) % 4]; area += p.x * o.y - o.x * p.y; }
    if (area < 0) q = [q[0], q[3], q[2], q[1]];
    area = Math.abs(area) / 2;
    // sanity: sides not degenerate, the quad is reasonably square
    var minS = 1e9, maxS = 0;
    for (i = 0; i < 4; i++) {
      var a = q[i], b2 = q[(i + 1) % 4], L = Math.hypot(b2.x - a.x, b2.y - a.y);
      minS = Math.min(minS, L); maxS = Math.max(maxS, L);
    }
    if (minS < 10 || maxS / minS > 3 || area < 150) return null;
    return q;
  }

  function sampleCells(gray, w, h, q) {
    var H = solveH(UNIT, q); if (!H) return null;
    var vals = new Array(49), k = 0;
    for (var r = 0; r < 7; r++) for (var c = 0; c < 7; c++) {
      var sum = 0, n = 0;
      for (var sy = 0; sy < 3; sy++) for (var sx = 0; sx < 3; sx++) {
        var p = applyH(H, (c + 0.3 + sx * 0.2) / 7, (r + 0.3 + sy * 0.2) / 7);
        var px = Math.round(p.x), py = Math.round(p.y);
        if (px < 0 || py < 0 || px >= w || py >= h) return null;
        sum += gray[py * w + px]; n++;
      }
      vals[k++] = sum / n;
    }
    return { vals: vals, H: H };
  }

  function decodeQuad(gray, w, h, q) {
    for (var rot = 0; rot < 4; rot++) {
      var cs = [q[rot % 4], q[(rot + 1) % 4], q[(rot + 2) % 4], q[(rot + 3) % 4]];
      var smp = sampleCells(gray, w, h, cs); if (!smp) return null;
      var v = smp.vals, mn = 255, mx = 0, i;
      for (i = 0; i < 49; i++) { if (v[i] < mn) mn = v[i]; if (v[i] > mx) mx = v[i]; }
      if (mx - mn < 40) return null;
      var t = (mn + mx) / 2, borderErr = 0, b = [];
      for (var r = 0; r < 7; r++) for (var c = 0; c < 7; c++) {
        var white = v[r * 7 + c] > t ? 1 : 0;
        if (r === 0 || c === 0 || r === 6 || c === 6) { if (white) borderErr++; }
        else { if (!b[r - 1]) b[r - 1] = []; b[r - 1][c - 1] = white; }
      }
      if (borderErr > 1) return null;      // the border does not depend on the rotation
      var id = decodeBits(b);
      if (id >= 0) return { id: id, corners: cs, center: applyH(smp.H, 0.5, 0.5) };
    }
    return null;
  }

  // gray: Uint8Array w*h. Returns [{ id, corners: [4 × {x,y}], center: {x,y} }].
  function detect(gray, w, h) {
    ensureBuf(w, h);
    var I = buf.integ, bin = buf.bin, lab = buf.lab, st = buf.stack, x, y, W1 = w + 1;
    for (y = 0; y < h; y++) {
      var row = 0;
      for (x = 0; x < w; x++) { row += gray[y * w + x]; I[(y + 1) * W1 + x + 1] = I[y * W1 + x + 1] + row; }
    }
    var R = Math.max(6, Math.round(Math.min(w, h) / 16)), C = 7;
    for (y = 0; y < h; y++) {
      var y0 = Math.max(0, y - R), y1 = Math.min(h, y + R + 1);
      for (x = 0; x < w; x++) {
        var x0 = Math.max(0, x - R), x1 = Math.min(w, x + R + 1);
        var s = I[y1 * W1 + x1] - I[y0 * W1 + x1] - I[y1 * W1 + x0] + I[y0 * W1 + x0];
        var mean = s / ((x1 - x0) * (y1 - y0));
        bin[y * w + x] = gray[y * w + x] < mean - C ? 1 : 0;
      }
    }
    lab.fill(0);
    var out = [], label = 0, maxSide = Math.max(w, h) * 0.7;
    for (var p0 = 0; p0 < w * h; p0++) {
      if (!bin[p0] || lab[p0]) continue;
      label++;
      var sp = 0, count = 0, minx = w, miny = h, maxx = 0, maxy = 0, bxs = [], bys = [];
      st[sp++] = p0; lab[p0] = label;
      while (sp) {
        var p = st[--sp], px = p % w, py = (p - px) / w, edge = false;
        count++;
        if (px < minx) minx = px; if (px > maxx) maxx = px; if (py < miny) miny = py; if (py > maxy) maxy = py;
        // 4-neighbours
        if (px > 0) { if (bin[p - 1]) { if (!lab[p - 1]) { lab[p - 1] = label; st[sp++] = p - 1; } } else edge = true; } else edge = true;
        if (px < w - 1) { if (bin[p + 1]) { if (!lab[p + 1]) { lab[p + 1] = label; st[sp++] = p + 1; } } else edge = true; } else edge = true;
        if (py > 0) { if (bin[p - w]) { if (!lab[p - w]) { lab[p - w] = label; st[sp++] = p - w; } } else edge = true; } else edge = true;
        if (py < h - 1) { if (bin[p + w]) { if (!lab[p + w]) { lab[p + w] = label; st[sp++] = p + w; } } else edge = true; } else edge = true;
        if (edge && bxs.length < 20000) { bxs.push(px); bys.push(py); }
      }
      var bw = maxx - minx + 1, bh = maxy - miny + 1;
      if (count < 60 || bw < 12 || bh < 12 || bw > maxSide || bh > maxSide) continue;
      if (minx === 0 || miny === 0 || maxx === w - 1 || maxy === h - 1) continue;   // cut by the frame edge
      var q = quadFromPoints(bxs, bys); if (!q) continue;
      var m = decodeQuad(gray, w, h, q); if (!m) continue;
      m.size = Math.hypot(q[2].x - q[0].x, q[2].y - q[0].y);
      out.push(m);
    }
    // one marker per id: keep the largest
    var best = {};
    out.forEach(function (m) { if (!best[m.id] || best[m.id].size < m.size) best[m.id] = m; });
    return Object.keys(best).map(function (k) { return best[k]; });
  }

  // ================================================================== map textures
  function texFor(body) {
    if (tex[body]) return tex[body];
    var rec = tex[body] = { canvas: null, state: "loading" };
    var G = window.Globe && window.Globe.surfaceTextures;
    try { rec.canvas = G ? G.procedural(body) : null; } catch (e) { rec.canvas = null; }
    if (!rec.canvas) {                      // last resort: flat tint, clearly not imagery
      var c = document.createElement("canvas"); c.width = 512; c.height = 256;
      var x = c.getContext("2d"); x.fillStyle = body === "mars" ? "#9a5536" : "#8a8f99"; x.fillRect(0, 0, 512, 256);
      rec.canvas = c;
    }
    var urls = (host && host.tiles) ? host.tiles(body) : [];
    function attempt() {
      if (!G || !urls.length) { rec.state = "fallback"; render(); return; }
      G.loadTiles(urls[0], 2, 14000).then(function (cv) { rec.canvas = cv; rec.state = "nasa"; render(); },
        function () { urls.shift(); attempt(); });
    }
    attempt();
    return rec;
  }

  // ================================================================== drawing
  function solve3(s0, s1, s2, d0, d1, d2) {   // affine source triangle -> destination triangle
    var den = s0.x * (s1.y - s2.y) + s1.x * (s2.y - s0.y) + s2.x * (s0.y - s1.y);
    if (Math.abs(den) < 1e-9) return null;
    function row(a, b, c) {
      return [(a * (s1.y - s2.y) + b * (s2.y - s0.y) + c * (s0.y - s1.y)) / den,
              (a * (s2.x - s1.x) + b * (s0.x - s2.x) + c * (s1.x - s0.x)) / den,
              (a * (s1.x * s2.y - s2.x * s1.y) + b * (s2.x * s0.y - s0.x * s2.y) + c * (s0.x * s1.y - s1.x * s0.y)) / den];
    }
    var X = row(d0.x, d1.x, d2.x), Y = row(d0.y, d1.y, d2.y);
    return [X[0], Y[0], X[1], Y[1], X[2], Y[2]];
  }
  function tri(ctx, img, s0, s1, s2, d0, d1, d2, sx, sy, sw, sh) {
    var m = solve3(s0, s1, s2, d0, d1, d2); if (!m) return;
    var cx = (d0.x + d1.x + d2.x) / 3, cy = (d0.y + d1.y + d2.y) / 3;
    function grow(p) { var dx = p.x - cx, dy = p.y - cy, L = Math.hypot(dx, dy) || 1; return { x: p.x + dx / L * 0.7, y: p.y + dy / L * 0.7 }; }
    var a = grow(d0), b = grow(d1), c = grow(d2);
    ctx.save();
    ctx.beginPath(); ctx.moveTo(a.x, a.y); ctx.lineTo(b.x, b.y); ctx.lineTo(c.x, c.y); ctx.closePath(); ctx.clip();
    ctx.transform(m[0], m[1], m[2], m[3], m[4], m[5]);
    ctx.drawImage(img, sx, sy, sw, sh, sx, sy, sw, sh);
    ctx.restore();
  }
  function drawMap(ctx, img, Hd) {
    var NX = 16, NY = 8, W = img.width, Hh = img.height, i, j, P = [];
    for (j = 0; j <= NY; j++) { P.push([]); for (i = 0; i <= NX; i++) P[j].push(applyH(Hd, i / NX, j / NY)); }
    for (j = 0; j < NY; j++) for (i = 0; i < NX; i++) {
      var x0 = i * W / NX, x1 = (i + 1) * W / NX, y0 = j * Hh / NY, y1 = (j + 1) * Hh / NY;
      var sx = Math.max(0, Math.floor(x0) - 1), sy = Math.max(0, Math.floor(y0) - 1);
      var sw = Math.min(W, Math.ceil(x1) + 1) - sx, sh = Math.min(Hh, Math.ceil(y1) + 1) - sy;
      var a = { x: x0, y: y0 }, b = { x: x1, y: y0 }, c = { x: x1, y: y1 }, d = { x: x0, y: y1 };
      tri(ctx, img, a, b, c, P[j][i], P[j][i + 1], P[j + 1][i + 1], sx, sy, sw, sh);
      tri(ctx, img, a, c, d, P[j][i], P[j + 1][i + 1], P[j + 1][i], sx, sy, sw, sh);
    }
  }
  function objUV(o) { return { u: (o.lon + 180) / 360, v: (90 - o.lat) / 180 }; }
  function objectsHere() { return host.objects().filter(function (o) { return o.planet === S.body; }); }
  // distance in fractions of the table width (the table is 2:1, so v counts half)
  function dist(a, b) { var du = a.u - b.u, dv = (a.v - b.v) * 0.5; return Math.sqrt(du * du + dv * dv); }

  function stageSize() {
    var r = E.stage.getBoundingClientRect(), dpr = Math.min(2, window.devicePixelRatio || 1);
    var w = Math.max(1, Math.round(r.width)), h = Math.max(1, Math.round(r.height));
    if (E.cv.width !== Math.round(w * dpr) || E.cv.height !== Math.round(h * dpr)) {
      E.cv.width = Math.round(w * dpr); E.cv.height = Math.round(h * dpr);
    }
    return { w: w, h: h, dpr: dpr };
  }
  function demoRect(sz) {
    var pad = Math.min(24, sz.w * 0.04), aw = sz.w - 2 * pad, ah = sz.h - 2 * pad;
    var tw = Math.min(aw, ah * 2), th = tw / 2;
    // portrait phone: map at the top, so the bottom-sheet card does not cover it
    var y = sz.h > sz.w * 1.1 ? pad : (sz.h - th) / 2;
    return { x: (sz.w - tw) / 2, y: y, w: tw, h: th };
  }

  var lastHd = null;
  function render() {
    if (!built || !S.shown) return;
    var sz = stageSize(), ctx = E.cv.getContext("2d");
    ctx.setTransform(sz.dpr, 0, 0, sz.dpr, 0, 0);
    ctx.clearRect(0, 0, sz.w, sz.h);
    var Hd = null, toD = null, rec = texFor(S.body);
    if (S.mode === "camera" && E.video.videoWidth) {
      var vw = E.video.videoWidth, vh = E.video.videoHeight, s = Math.min(sz.w / vw, sz.h / vh);
      var ox = (sz.w - vw * s) / 2, oy = (sz.h - vh * s) / 2, k = work ? work.width / vw : 1;
      ctx.drawImage(E.video, ox, oy, vw * s, vh * s);
      toD = function (p) { return { x: p.x / k * s + ox, y: p.y / k * s + oy }; };
      if (S.table) Hd = solveH(UNIT, S.table.map(toD));
      // detected markers: thin outline, helps aiming the camera
      ctx.lineWidth = 2;
      S.found.forEach(function (m) {
        ctx.strokeStyle = m.id === ROBOT_ID ? "#5fd39b" : "#f2c14e";
        ctx.beginPath(); m.corners.forEach(function (c, i) { var d = toD(c); if (i) ctx.lineTo(d.x, d.y); else ctx.moveTo(d.x, d.y); }); ctx.closePath(); ctx.stroke();
      });
    } else {
      var R = demoRect(sz);
      Hd = solveH(UNIT, [{ x: R.x, y: R.y }, { x: R.x + R.w, y: R.y }, { x: R.x + R.w, y: R.y + R.h }, { x: R.x, y: R.y + R.h }]);
    }
    lastHd = Hd;
    if (Hd) {
      ctx.globalAlpha = S.mode === "camera" ? 0.88 : 1;
      drawMap(ctx, rec.canvas, Hd);
      ctx.globalAlpha = 1;
      var c0 = applyH(Hd, 0, 0), c1 = applyH(Hd, 1, 0), tw = Math.hypot(c1.x - c0.x, c1.y - c0.y);
      ctx.strokeStyle = "rgba(255,255,255,0.35)"; ctx.lineWidth = 1;
      ctx.beginPath(); UNIT.forEach(function (u, i) { var p = applyH(Hd, u.x, u.y); if (i) ctx.lineTo(p.x, p.y); else ctx.moveTo(p.x, p.y); }); ctx.closePath(); ctx.stroke();
      drawPins(ctx, Hd, tw);
      var ruv = robotUV();
      if (ruv) drawRobot(ctx, Hd, ruv, tw);
    }
  }

  function drawPins(ctx, Hd, tw) {
    var r = Math.max(4, tw * 0.009);
    objectsHere().forEach(function (o) {
      var uv = objUV(o), p = applyH(Hd, uv.u, uv.v), on = o.id === S.activeId;
      ctx.beginPath(); ctx.arc(p.x, p.y, on ? r * 1.7 : r, 0, Math.PI * 2);
      ctx.fillStyle = host.statusColor(o); ctx.fill();
      ctx.lineWidth = on ? 3 : 1.5; ctx.strokeStyle = on ? "#ffffff" : "rgba(7,11,20,0.85)";
      if (o.accuracy && o.accuracy.level === "area") ctx.setLineDash([3, 3]);
      ctx.stroke(); ctx.setLineDash([]);
      if (on) {
        ctx.beginPath(); ctx.arc(p.x, p.y, r * 3, 0, Math.PI * 2);
        ctx.strokeStyle = host.statusColor(o); ctx.lineWidth = 2; ctx.stroke();
        var name = host.loc(o).name;
        ctx.font = "600 13px 'IBM Plex Sans', system-ui, sans-serif";
        var tw2 = ctx.measureText(name).width, cw = E.cv.clientWidth || 9999;
        var lx = Math.min(Math.max(p.x, tw2 / 2 + 8), cw - tw2 / 2 - 8);   // keep the label inside the picture
        ctx.fillStyle = "rgba(7,11,20,0.82)"; ctx.fillRect(lx - tw2 / 2 - 6, p.y - r * 3 - 26, tw2 + 12, 20);
        ctx.fillStyle = "#fff"; ctx.textAlign = "center"; ctx.textBaseline = "middle"; ctx.fillText(name, lx, p.y - r * 3 - 16);
      }
    });
  }
  function drawRobot(ctx, Hd, uv, tw) {
    var p = applyH(Hd, uv.u, uv.v), q = applyH(Hd, uv.u + S.radius, uv.v), rr = Math.hypot(q.x - p.x, q.y - p.y);
    ctx.beginPath(); ctx.arc(p.x, p.y, rr, 0, Math.PI * 2);
    ctx.setLineDash([5, 5]); ctx.strokeStyle = "rgba(95,211,155,0.9)"; ctx.lineWidth = 1.5; ctx.stroke(); ctx.setLineDash([]);
    var R = Math.max(9, tw * 0.018);
    ctx.fillStyle = "rgba(95,211,155,0.25)"; ctx.beginPath(); ctx.arc(p.x, p.y, R, 0, Math.PI * 2); ctx.fill();
    ctx.lineWidth = 2.5; ctx.strokeStyle = "#5fd39b"; ctx.stroke();
    ctx.beginPath(); ctx.moveTo(p.x - R * 0.6, p.y); ctx.lineTo(p.x + R * 0.6, p.y); ctx.moveTo(p.x, p.y - R * 0.6); ctx.lineTo(p.x, p.y + R * 0.6); ctx.stroke();
    ctx.font = "600 12px 'IBM Plex Sans', system-ui, sans-serif"; ctx.textAlign = "center"; ctx.textBaseline = "top";
    ctx.fillStyle = "#5fd39b"; ctx.fillText(T("art.robot"), p.x, p.y + R + 4);
  }

